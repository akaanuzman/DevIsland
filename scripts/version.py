#!/usr/bin/env python3
"""One source for bundle, helper, archive and release versions."""
import json, pathlib, plistlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
def metadata():
    v=json.loads((ROOT/'Resources/version.json').read_text())
    if not re.fullmatch(r'\d+\.\d+\.\d+(?:-beta\.\d+)?',v['version']) or type(v['build']) is not int or v['build']<=10:
        raise ValueError('Invalid version or non-increasing baseline build')
    return v
if __name__=='__main__':
    v=metadata()
    if len(sys.argv)>1 and sys.argv[1]=='--generate':
        target=ROOT/'Sources/DevIslandCore/BuildInfo.swift'
        data='// Generated by scripts/version.py from Resources/version.json.\npublic enum BuildInfo {\n    public static let version = '+json.dumps(v['version'])+'\n    public static let build = '+str(v['build'])+'\n}\n'
        if not target.exists() or target.read_text()!=data: target.write_text(data)
        p=ROOT/'Resources/Info.plist'; info=plistlib.loads(p.read_bytes()); info['CFBundleShortVersionString']=v['version']; info['CFBundleVersion']=str(v['build']); p.write_bytes(plistlib.dumps(info))
    else: print(v[sys.argv[1]] if len(sys.argv)>1 else json.dumps(v))
